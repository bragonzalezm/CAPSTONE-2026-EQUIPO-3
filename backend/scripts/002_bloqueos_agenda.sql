BEGIN;
CREATE TABLE IF NOT EXISTS bloqueo_horario (
 id_bloqueo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rut_especialista varchar(10) NOT NULL REFERENCES usuario(rut),
 fecha date NOT NULL, hora_inicio time NOT NULL, hora_fin time NOT NULL,
 motivo varchar(300) NOT NULL DEFAULT '',
 CHECK(hora_inicio >= TIME '10:00' AND hora_fin <= TIME '19:00' AND hora_fin > hora_inicio),
 UNIQUE(rut_especialista,fecha,hora_inicio,hora_fin)
);
CREATE INDEX IF NOT EXISTS bloqueo_horario_fecha_idx ON bloqueo_horario(rut_especialista,fecha);
COMMIT;
